export function getSubcategory(category: string, keyword: string): string {
  const rules = CATEGORY_RULES[category];
  if (!rules) return '';

  const lowerKw = keyword.toLowerCase();
  for (const [subcat, patterns] of rules) {
    if (patterns.some(p => lowerKw.includes(p))) {
      return subcat;
    }
  }
  return '기타';
}

// 해당 카테고리에 세부분류가 있는지 확인
export function hasSubcategories(category: string): boolean {
  return !!CATEGORY_RULES[category];
}

// 카테고리의 세부분류 목록 반환
export function getSubcategoryList(category: string): string[] {
  const rules = CATEGORY_RULES[category];
  if (!rules) return [];
  return rules.map(([subcat]) => subcat);
}
