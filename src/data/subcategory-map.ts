// ─── 카테고리 → 세부분류 규칙 매핑 ───
const CATEGORY_RULES: Record<string, SubcategoryRule> = {
  '도서': BOOK_SUBCATEGORIES,
  '뷰티/패션': BEAUTY_SUBCATEGORIES,
  '패션/뷰티': BEAUTY_SUBCATEGORIES,
  '뷰티_패션': BEAUTY_SUBCATEGORIES,
  '여행': TRAVEL_SUBCATEGORIES,
  '맛집': FOOD_SUBCATEGORIES,
  '음식': FOOD_SUBCATEGORIES,
  '생활건강': LIVING_SUBCATEGORIES,
  '생활/건강': LIVING_SUBCATEGORIES,
  '리빙': LIVING_SUBCATEGORIES,
  'IT/테크': IT_SUBCATEGORIES,
  'IT': IT_SUBCATEGORIES,
  '테크': IT_SUBCATEGORIES,
  '요리': COOKING_SUBCATEGORIES,
};

export function getSubcategory(category: string, keyword: string): string {
  const rules = CATEGORY_RULES[category];
  if (!rules) return '';

  const lowerKw = keyword.toLowerCase();
  for (const [subcat, patterns] of rules) {
    if (patterns.some(p => lowerKw.includes(p))) {
      return subcat;
    }
  }
  return '기타';
}

// 해당 카테고리에 세부분류가 있는지 확인
export function hasSubcategories(category: string): boolean {
  return !!CATEGORY_RULES[category];
}

// 카테고리의 세부분류 목록 반환
export function getSubcategoryList(category: string): string[] {
  const rules = CATEGORY_RULES[category];
  if (!rules) return [];
  return rules.map(([subcat]) => subcat);
}
